#!/usr/bin/env python3
"""lesson — the record that lets this skill learn from its own runs.

  lesson.py add --source user|check|tool|outcome --what "..." --lesson "..." [--evidence "..."]
  lesson.py list
  lesson.py retire <id> --why "folded into SKILL.md step 3" | "was wrong: ..."

The skill keeps `lessons.jsonl` (the record, append-only) and `LESSONS.md` (generated from it, read
at the start of every run). `add` merges a lesson into an existing one when they say the same thing
and counts how often it was seen, so a mistake made twice stands out. LESSONS.md lists the 25 that
matter most (the user's corrections first, then the most often seen, then the newest) and marks the
ones that are due to be written into the skill itself. The rules for what may be recorded are in
LEARNING.md. Standard library only.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
SOURCES = {
    "user": "the user corrected or instructed",
    "check": "a script or check failed",
    "tool": "a tool behaved differently from what the skill says",
    "outcome": "learned later from a real result",
}
SHOWN = 25


def die(msg: str) -> None:
    raise SystemExit(f"lesson: {msg}")


def load(d: Path) -> list[dict]:
    p = d / "lessons.jsonl"
    return [json.loads(line) for line in p.read_text().splitlines() if line.strip()] if p.exists() else []


def save(d: Path, items: list[dict]) -> None:
    (d / "lessons.jsonl").write_text("".join(json.dumps(i, ensure_ascii=False) + "\n" for i in items))
    render(d, items)


def tokens(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", text.lower()) if len(w) > 3}


def same(a: str, b: str) -> bool:
    ta, tb = tokens(a), tokens(b)
    return bool(ta and tb) and len(ta & tb) / len(ta | tb) >= 0.55


def render(d: Path, items: list[dict]) -> None:
    live = [i for i in items if not i.get("retired")]
    live.sort(key=lambda i: i["dates"][-1], reverse=True)          # newest first, then (stable sort)
    live.sort(key=lambda i: (i["source"] != "user", -i["seen"]))    # the user's corrections, then most seen
    out = ["# Lessons", "",
           "Generated by `scripts/lesson.py` from `lessons.jsonl`. Do not edit by hand.",
           "Read before every run. Each is what went wrong once and what to do instead. The request in",
           "front of you and SKILL.md's safety rules come first.", ""]
    if not live:
        out.append("No lessons yet.")
    for i in live[:SHOWN]:
        due = "  **Due to be written into the skill.**" if i["seen"] >= 2 or i["source"] == "user" else ""
        seen = f", seen {i['seen']} times" if i["seen"] > 1 else ""
        out.append(f"- **L{i['id']}** {i['lesson']}")
        out.append(f"  - What happened: {i['what']}")
        if i.get("evidence"):
            out.append(f"  - Evidence: {i['evidence']}")
        out.append(f"  - Source: {SOURCES[i['source']]} ({i['dates'][-1]}{seen}).{due}")
    if len(live) > SHOWN:
        out.append(f"\n{len(live) - SHOWN} older lessons are in `lessons.jsonl`.")
    retired = [i for i in items if i.get("retired")]
    if retired:
        out += ["", "## Retired", ""] + [f"- L{i['id']} ({i['retired']['date']}): {i['retired']['why']}" for i in retired[-15:]]
    (d / "LESSONS.md").write_text("\n".join(out) + "\n")


def cmd_add(a: argparse.Namespace) -> None:
    d = SKILL
    if len(a.lesson.split()) < 5 or len(a.what.split()) < 4:
        die("say what happened and what to do instead, in a full sentence each")
    items = load(d)
    today = dt.date.today().isoformat()
    for i in items:
        if not i.get("retired") and same(i["lesson"], a.lesson):
            i["seen"] += 1
            i["dates"].append(today)
            if a.source == "user":
                i["source"] = "user"
            if a.evidence:
                i["evidence"] = a.evidence
            save(d, items)
            print(f"L{i['id']} seen again ({i['seen']} times): it is due to be written into the skill itself")
            return
    new = {"id": max((i["id"] for i in items), default=0) + 1, "source": a.source, "what": a.what.strip(),
           "lesson": a.lesson.strip(), "evidence": (a.evidence or "").strip(), "seen": 1, "dates": [today]}
    items.append(new)
    save(d, items)
    print(f"recorded L{new['id']}" + (": from the user, so write it into the skill now" if a.source == "user" else ""))


def cmd_list(a: argparse.Namespace) -> None:
    d = SKILL
    render(d, load(d))
    print((d / "LESSONS.md").read_text())


def cmd_retire(a: argparse.Namespace) -> None:
    d = SKILL
    items = load(d)
    hit = [i for i in items if i["id"] == int(str(a.id).lstrip("Ll"))]
    if not hit:
        die(f"no lesson {a.id}")
    hit[0]["retired"] = {"date": dt.date.today().isoformat(), "why": a.why}
    save(d, items)
    print(f"retired L{hit[0]['id']}: {a.why}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("add")
    p.add_argument("--source", required=True, choices=sorted(SOURCES))
    p.add_argument("--what", required=True)
    p.add_argument("--lesson", required=True)
    p.add_argument("--evidence")
    p.set_defaults(fn=cmd_add)
    p = sub.add_parser("list")
    p.set_defaults(fn=cmd_list)
    p = sub.add_parser("retire")
    p.add_argument("id")
    p.add_argument("--why", required=True)
    p.set_defaults(fn=cmd_retire)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
